// Regenerates Packages/studio.sable.toolbox.qa/Editor/Data/performance-limits.json from the VRChat
// SDK's own rank thresholds, so a VRChat limits change is a data update, not a code change.
//
//   node tools/gen-performance-limits.mjs <path to com.vrchat.base package>
//
// Reads Runtime/VRCSDK/Dependencies/VRChat/Resources/Validation/Performance/StatsLevels/{Windows,Quest}/
// {Excellent,Good,Medium,Poor}_*.asset. Metric ids are the SDK's AvatarPerformanceStats field names
// (nested PhysBone stats as "physBone.<field>").

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const base = process.argv[2];
if (!base) { console.error("usage: node tools/gen-performance-limits.mjs <com.vrchat.base path>"); process.exit(1); }

const levelsDir = join(base, "Runtime/VRCSDK/Dependencies/VRChat/Resources/Validation/Performance/StatsLevels");
const sdkVersion = JSON.parse(readFileSync(join(base, "package.json"), "utf8")).version;
const ranks = ["Excellent", "Good", "Medium", "Poor"];

// Display labels for known metrics; unknown future metrics fall back to their id.
const labels = {
  polyCount: "Triangles", textureMegabytes: "Texture memory (MB)", skinnedMeshCount: "Skinned meshes",
  meshCount: "Basic meshes", materialCount: "Material slots", animatorCount: "Animators", boneCount: "Bones",
  lightCount: "Lights", particleSystemCount: "Particle systems", particleTotalCount: "Total max particles",
  particleMaxMeshPolyCount: "Mesh particle max polys", particleTrailsEnabled: "Particle trails",
  particleCollisionEnabled: "Particle collision", trailRendererCount: "Trail renderers",
  lineRendererCount: "Line renderers", clothCount: "Cloths", clothMaxVertices: "Total cloth vertices",
  physicsColliderCount: "Physics colliders", physicsRigidbodyCount: "Physics rigidbodies",
  audioSourceCount: "Audio sources", "physBone.componentCount": "PhysBone components",
  "physBone.transformCount": "PhysBone transforms", "physBone.colliderCount": "PhysBone colliders",
  "physBone.collisionCheckCount": "PhysBone collision checks", contactCount: "Contacts",
  constraintsCount: "Constraints", constraintDepth: "Constraint depth", raycastCount: "Raycasts",
};

// Flat "key: number" lines, with one level of nesting for blocks like "physBone:".
function parseLevel(path) {
  const values = {};
  let parent = null;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const m = line.match(/^(\s*)([A-Za-z]\w*):\s*(.*)$/);
    if (!m) continue;
    const [, indent, key, raw] = m;
    if (indent.length <= 2) parent = null;
    if (raw === "" && indent.length === 2) { parent = key; continue; }
    if (!/^-?\d+(\.\d+)?$/.test(raw)) continue;
    if (indent.length === 2 && !key.startsWith("m_")) values[key] = Number(raw);
    else if (indent.length === 4 && parent) values[`${parent}.${key}`] = Number(raw);
  }
  return values;
}

function platform(dir, suffix) {
  const levels = ranks.map(r => parseLevel(join(levelsDir, dir, `${r}_${suffix}.asset`)));
  const ids = Object.keys(levels[0]);
  return ids.map(id => ({
    id,
    label: labels[id] ?? id,
    excellent: levels[0][id], good: levels[1][id], medium: levels[2][id], poor: levels[3][id],
  }));
}

const out = {
  version: 1,
  _comment: `Generated by tools/gen-performance-limits.mjs from VRChat SDK com.vrchat.base ${sdkVersion}. ` +
    "A value above 'poor' is Very Poor. Size limits are from the VRChat docs (spec: Performance budget).",
  sdkVersion,
  platforms: [
    { id: "pc", name: "PC", downloadLimitMB: 200, memoryLimitMB: 500, metrics: platform("Windows", "Windows") },
    { id: "android", name: "Android", downloadLimitMB: 10, memoryLimitMB: 40, metrics: platform("Quest", "Quest") },
  ],
};

const target = join(dirname(fileURLToPath(import.meta.url)), "..",
  "Packages/studio.sable.toolbox.qa/Editor/Data/performance-limits.json");
writeFileSync(target, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${target}: ${out.platforms.map(p => `${p.id} ${p.metrics.length} metrics`).join(", ")}`);
